    #[test]
    fn env_templates_are_source_and_bom_marked_env_files_are_read() {
        let repo = plain(&[
            ("src/a.rs", "fn main() {}"),
            (".env.example", "API_KEY=\n"),
            (".env", "\u{feff}FIRST_KEY=1\nSECOND_KEY=2\n"),
        ]);

        let s = select(repo.path(), &[]).unwrap();

        assert_eq!(rels(&s.files), [".env.example", "src/a.rs"]);
        assert_eq!(s.env_names, ["API_KEY", "FIRST_KEY", "SECOND_KEY"]);
    }

    #[test]
    fn utf16_env_files_are_decoded() {
        let repo = plain(&[("src/a.rs", "x")]);
        let mut bytes = vec![0xFF, 0xFE];
        for unit in "WIDE_KEY=1\r\n".encode_utf16() {
            bytes.extend_from_slice(&unit.to_le_bytes());
        }
        std::fs::write(repo.path().join(".env"), bytes).unwrap();

        assert_eq!(select(repo.path(), &[]).unwrap().env_names, ["WIDE_KEY"]);
    }

    #[test]
    fn output_dirs_match_with_a_leading_dot_slash() {
        let repo = plain(&[("src/a.rs", "x"), ("build/out.js", "y")]);

        let s = select(repo.path(), &["./build/"]).unwrap();

        assert_eq!(rels(&s.files), ["src/a.rs"]);
    }

    #[test]
    fn the_bundle_lives_in_a_private_directory_that_remove_bundle_cleans_up() {
        let repo = git_repo(&[("src/a.rs", "one")]);

        let bundle = select(repo.path(), &[]).unwrap().bundle.expect("bundle");

        let dir = bundle.parent().unwrap().to_path_buf();
        assert_ne!(dir, std::env::temp_dir(), "must not sit loose in temp");
        assert!(dir.is_dir());
        remove_bundle(&bundle);
        assert!(!dir.exists());
    }
